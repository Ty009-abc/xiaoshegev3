function _generateVariants(title, matrix) {
  const prefixes = ANGLE_PREFIXES[matrix] || ['换个思路：']
  const variants = []
  for (let i = 0; i < 3; i++) {
    variants.push({ title: `${prefixes[i]}${title}` })
  }
  return variants
}

