// Topic Factory — 从模板生成完整选题池
// ═══════════════════════════════════════════

function _generateTopics() {
  const topics = []
  let idCounter = 0

  const addTopic = (matrix, key, title, score) => {
    idCounter++
    topics.push({
      id: `${matrix}_${String(idCounter).padStart(4, '0')}`,
      key: key.slice(0, 30),
      title,
      matrix,
      score: score || 75 + Math.floor(Math.random() * 15),
      tag: '',
    })
  }

  // 生产赌场选题
  CASINO_TEMPLATES.forEach(tpl => {
    tpl.suffixes.forEach(suffix => {
      const title = `${tpl.prefix}，${suffix}`
      addTopic('casino', tpl.prefix.slice(0, 20), title)
    })
  })

  // 生产认知选题
  COGNITION_TEMPLATES.forEach(tpl => {
    tpl.suffixes.forEach(suffix => {
      const title = `${tpl.prefix}：${suffix}`
      addTopic('cognition', tpl.prefix.slice(0, 20), title)
    })
  })

  // 生产AI选题
  AI_TEMPLATES.forEach(tpl => {
    tpl.suffixes.forEach(suffix => {
      const title = `${tpl.prefix}——${suffix}`
      addTopic('ai', tpl.prefix.slice(0, 20), title)
    })
  })

  // 生产热点选题
  TRENDING_TEMPLATES.forEach(tpl => {
    tpl.suffixes.forEach(suffix => {
      const title = `${tpl.prefix}：${suffix}`
      addTopic('trending', tpl.prefix.slice(0, 20), title)
    })
  })

  // ── 扩展模式：每个已有选题生成3-4个变体 ──
  const baseTopics = [...topics]
  baseTopics.forEach(t => {
    const variants = _generateVariants(t.title, t.matrix)
    variants.forEach(v => addTopic(t.matrix, v.title.slice(0, 20), v.title, t.score - Math.floor(Math.random()*5)))
  })

  // 二次扩展：对变体再生成一次角度切换
  const round2 = [...topics]
  round2.forEach(t => {
    const angle = ANGLES[t.matrix][Math.floor(Math.random() * ANGLES[t.matrix].length)]
    const newTitle = `${t.title}—${angle}`
    addTopic(t.matrix, newTitle.slice(0, 30), newTitle, t.score - Math.floor(Math.random()*8))
  })

  return topics
}

