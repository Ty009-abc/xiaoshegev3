/**
 * 根据日期获取当日暴击（所有用户同一天看到同一条）
 * 算法：YYYYMMDD % 50 → 定向锚定索引
 * @returns {Object} 当日暴击条目（id=今天日期）
 */
function getTodayStrike() {
  const now = new Date();
  const y = now.getFullYear();
  const m = String(now.getMonth() + 1).padStart(2, '0');
  const d = String(now.getDate()).padStart(2, '0');
  const dateStr = `${y}${m}${d}`;
  const idx = parseInt(dateStr, 10) % STRIKE_POOL.length;
  const entry = STRIKE_POOL[idx];
  return { ...entry, id: dateStr };
}

